/* Captain Busara – site script (vanilla JS, no dependencies).
   Texts and the WhatsApp number come from <script id="siteConfig"> generated by tools/build.py. */
(function () {
  'use strict';

  var cfgEl = document.getElementById('siteConfig');
  var CFG = { lang: 'en', whatsapp: '', msg: {}, ui: {} };
  try { if (cfgEl) CFG = JSON.parse(cfgEl.textContent); } catch (e) { /* use defaults */ }

  function $(sel, root) { return (root || document).querySelector(sel); }
  function $$(sel, root) { return Array.prototype.slice.call((root || document).querySelectorAll(sel)); }
  function waLink(text) { return 'https://wa.me/' + CFG.whatsapp + '?text=' + encodeURIComponent(text); }
  function fmt(tpl, vars) { return String(tpl || '').replace(/\{(\w+)\}/g, function (_, k) { return vars[k] != null ? vars[k] : ''; }); }
  function pad(n) { return (n < 10 ? '0' : '') + n; }

  var store = {
    get: function (k) { try { return localStorage.getItem(k); } catch (e) { return null; } },
    set: function (k, v) { try { localStorage.setItem(k, v); } catch (e) { /* ignore */ } }
  };

  /* ---------- language preference ---------- */
  var page = document.body.getAttribute('data-page');
  $$('.lang__btn').forEach(function (a) {
    a.addEventListener('click', function () { store.set('lang', a.getAttribute('data-lang')); });
  });
  (function suggestPolish() {
    // First visit from a Polish browser (or a saved PL choice) lands on the Polish home page.
    if (page !== 'home' || CFG.lang !== 'en' || location.hash) return;
    var pref = store.get('lang');
    var browserPl = /^pl\b/i.test((navigator.language || '').toLowerCase());
    if (pref === 'pl' || (!pref && browserPl)) location.replace('pl/' + location.search);
  })();

  /* ---------- footer year ---------- */
  var year = $('#year');
  if (year) year.textContent = new Date().getFullYear();

  /* ---------- analytics (only active if Plausible is configured) ---------- */
  document.addEventListener('click', function (e) {
    var el = e.target.closest ? e.target.closest('[data-track]') : null;
    if (!el || typeof window.plausible !== 'function') return;
    try {
      var props = {};
      if (el.getAttribute('data-tour')) props.tour = el.getAttribute('data-tour');
      window.plausible(el.getAttribute('data-track'), { props: props });
    } catch (err) { /* ignore */ }
  });

  /* ---------- mobile menu ---------- */
  (function () {
    var burger = $('#burger');
    var menu = $('#mobileMenu');
    if (!burger || !menu) return;
    function setOpen(open) {
      menu.hidden = !open;
      burger.setAttribute('aria-expanded', open ? 'true' : 'false');
      burger.setAttribute('aria-label', burger.getAttribute(open ? 'data-close' : 'data-open'));
      burger.firstElementChild.textContent = open ? '✕' : '☰';
    }
    burger.addEventListener('click', function () { setOpen(menu.hidden); });
    $$('a', menu).forEach(function (a) { a.addEventListener('click', function () { setOpen(false); }); });
    document.addEventListener('keydown', function (e) { if (e.key === 'Escape' && !menu.hidden) { setOpen(false); burger.focus(); } });
  })();

  /* ---------- tour filters ---------- */
  (function () {
    var chips = $$('.chip');
    var cards = $$('#cards .card');
    if (!chips.length) return;
    chips.forEach(function (chip) {
      chip.addEventListener('click', function () {
        var f = chip.getAttribute('data-filter');
        chips.forEach(function (c) {
          var on = c === chip;
          c.classList.toggle('is-active', on);
          c.setAttribute('aria-pressed', on ? 'true' : 'false');
        });
        cards.forEach(function (card) {
          var cat = card.getAttribute('data-cat');
          card.hidden = !(f === 'all' || cat === f);
        });
      });
    });
  })();

  /* ---------- booking form -> WhatsApp ---------- */
  (function () {
    var form = $('#bookForm');
    if (!form) return;
    var el = {
      tour: $('#fTour'), date: $('#fDate'), people: $('#fPeople'), hotel: $('#fHotel'),
      type: $('#fType'), name: $('#fName'), notes: $('#fNotes')
    };
    var preview = $('#msgPreview');
    var copyBtn = $('#copyBtn');
    var m = CFG.msg;

    var t = new Date();
    el.date.min = t.getFullYear() + '-' + pad(t.getMonth() + 1) + '-' + pad(t.getDate());

    function val(node) { return (node.value || '').trim(); }
    function prettyDate(iso) {
      try {
        var d = new Date(iso + 'T00:00:00');
        if (isNaN(d.getTime())) return iso;
        return d.toLocaleDateString(CFG.lang === 'pl' ? 'pl-PL' : 'en-GB', { day: 'numeric', month: 'long', year: 'numeric' });
      } catch (e) { return iso; }
    }

    function buildMessage() {
      var any = Object.keys(el).some(function (k) { return val(el[k]); });
      if (!any) return m.m_default;
      var lines = [fmt(m.m_hi, { tour: val(el.tour) || m.m_anytour })];
      if (val(el.date)) lines.push(fmt(m.m_date, { v: prettyDate(val(el.date)) }));
      if (val(el.people)) lines.push(fmt(m.m_people, { v: val(el.people) }));
      if (val(el.hotel)) lines.push(fmt(m.m_hotel, { v: val(el.hotel) }));
      if (val(el.type)) lines.push(fmt(m.m_type, { v: val(el.type) }));
      if (val(el.name)) lines.push(fmt(m.m_name, { v: val(el.name) }));
      if (val(el.notes)) lines.push(fmt(m.m_notes, { v: val(el.notes) }));
      lines.push(m.m_bye);
      return lines.join('\n');
    }

    function refresh() { preview.textContent = buildMessage(); }
    ['input', 'change'].forEach(function (ev) { form.addEventListener(ev, refresh); });

    form.addEventListener('submit', function (e) {
      e.preventDefault();
      var a = document.createElement('a');
      a.href = waLink(buildMessage());
      a.target = '_blank';
      a.rel = 'noopener';
      document.body.appendChild(a);
      a.click();
      a.remove();
    });

    // Card buttons pre-select the tour and jump to the form
    $$('[data-book]').forEach(function (btn) {
      btn.addEventListener('click', function () {
        var name = btn.getAttribute('data-book');
        var found = false;
        Array.prototype.forEach.call(el.tour.options, function (o) { if (o.value === name) { el.tour.value = name; found = true; } });
        if (!found) el.tour.value = '';
        refresh();
        var target = $('#book');
        if (target) target.scrollIntoView({ behavior: 'smooth', block: 'start' });
        setTimeout(function () { try { el.date.focus({ preventScroll: true }); } catch (err) { /* ignore */ } }, 500);
      });
    });

    if (copyBtn) {
      copyBtn.addEventListener('click', function () {
        var text = preview.textContent.trim();
        function done(msg) {
          copyBtn.textContent = msg;
          setTimeout(function () { copyBtn.textContent = CFG.ui.copy; }, 1500);
        }
        if (navigator.clipboard && navigator.clipboard.writeText) {
          navigator.clipboard.writeText(text).then(function () { done(CFG.ui.copied); }, function () { done(CFG.ui.copyErr); });
        } else {
          done(CFG.ui.copyErr);
        }
      });
    }
    refresh();
  })();

  /* ---------- gallery lightbox ---------- */
  (function () {
    var dlg = $('#lightbox');
    var items = $$('.gal__item');
    if (!dlg || !items.length) return;
    var img = $('#lbImg'), cap = $('#lbCap');
    var idx = 0;
    var lastFocus = null;

    function show(i) {
      idx = (i + items.length) % items.length;
      var thumb = $('img', items[idx]);
      img.src = thumb.currentSrc || thumb.src;
      img.alt = thumb.alt;
      cap.textContent = thumb.alt;
      // warm the cache for the next image
      var next = $('img', items[(idx + 1) % items.length]);
      if (next) { var pre = new Image(); pre.src = next.currentSrc || next.src; }
    }
    function open(i) {
      lastFocus = document.activeElement;
      show(i);
      if (typeof dlg.showModal === 'function') dlg.showModal(); else dlg.setAttribute('open', '');
    }
    function close() {
      if (typeof dlg.close === 'function') dlg.close(); else dlg.removeAttribute('open');
    }
    items.forEach(function (btn, i) { btn.addEventListener('click', function () { open(i); }); });
    $('#lbClose').addEventListener('click', close);
    $('#lbPrev').addEventListener('click', function () { show(idx - 1); });
    $('#lbNext').addEventListener('click', function () { show(idx + 1); });
    dlg.addEventListener('click', function (e) { if (e.target === dlg) close(); });
    dlg.addEventListener('close', function () { if (lastFocus && lastFocus.focus) lastFocus.focus(); });
    document.addEventListener('keydown', function (e) {
      if (!dlg.open) return;
      if (e.key === 'ArrowLeft') show(idx - 1);
      else if (e.key === 'ArrowRight') show(idx + 1);
    });
  })();

  /* ---------- click-to-load map (no Google requests until the visitor asks) ---------- */
  (function () {
    var box = $('#mapBox');
    var btn = $('#mapLoad');
    if (!box || !btn) return;
    btn.addEventListener('click', function () {
      var f = document.createElement('iframe');
      f.src = box.getAttribute('data-src');
      f.title = box.getAttribute('data-title') || 'Map';
      f.loading = 'lazy';
      f.referrerPolicy = 'no-referrer-when-downgrade';
      f.setAttribute('allowfullscreen', '');
      box.innerHTML = '';
      box.appendChild(f);
    });
  })();

  /* ---------- hide the floating WhatsApp bar where it would cover forms/contact ---------- */
  (function () {
    var bar = $('#stickyBar');
    var targets = [$('#book'), $('#contact')].filter(Boolean);
    if (!bar || !targets.length || !('IntersectionObserver' in window)) return;
    var visible = {};
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) { visible[en.target.id] = en.isIntersecting; });
      bar.classList.toggle('is-hidden', Object.keys(visible).some(function (k) { return visible[k]; }));
    }, { threshold: 0.25 });
    targets.forEach(function (t) { io.observe(t); });
  })();
})();
